def seed_database(db: Session):
    """
    Seeds database with initial settings and 50+ sample products with pre-generated content.
    """
    # 1. Seed BrandSettings if not existing
    brand_settings = db.query(BrandSettings).first()
    if not brand_settings:
        brand_settings = BrandSettings(
            id=1,
            brand_name="CatalogCraft Retail",
            brand_voice="Professional, reliable, accurate, clear, customer-centric",
            preferred_words_json=json.dumps(["durable", "innovative", "premium quality", "ergonomic", "efficient", "sleek"]),
            prohibited_words_json=json.dumps(["best", "guaranteed", "number one", "perfect", "cheap", "miracle"]),
            mandatory_disclaimer="Product specifications and availability are subject to change without notice.",
            content_rules_json=json.dumps(["No unverifiable claims", "Highlight key customer benefits", "Include dimensions and specs when available"]),
            default_tone="Professional",
            default_language="English",
            default_word_count="Medium",
            keyword_policy="Natural Integration",
            allow_promotional_claims=False,
            max_keywords=5,
            include_feature_bullets=True
        )
        db.add(brand_settings)
        db.commit()

    # 2. Check if products exist
    existing_count = db.query(Product).count()
    if existing_count >= 50:
        return

    # Delete any residual test products if less than 50
    if existing_count > 0:
        db.query(Product).delete()
        db.commit()

    mock_gen = MockGenerator()
    brand_dict = {
        "brand_name": brand_settings.brand_name,
        "brand_voice": brand_settings.brand_voice,
        "preferred_words": brand_settings.preferred_words,
        "prohibited_words": brand_settings.prohibited_words,
    }

    tones = ["Professional", "Premium / Luxury", "Friendly", "Minimal", "Technical", "Eco-conscious"]
    statuses = ["Approved", "Approved", "Approved", "Draft", "Needs Review"]

    for idx, item in enumerate(SAMPLE_50_PRODUCTS):
        p = Product(
            sku=item["sku"],
            name=item["name"],
            brand=item["brand"],
            category=item["category"],
            price=item["price"],
            currency=item["currency"],
            features_json=json.dumps(item["features"]),
            specifications_json=json.dumps(item["specifications"]),
            target_audience=item.get("target_audience"),
            primary_keywords_json=json.dumps(item["primary_keywords"]),
            secondary_keywords_json=json.dumps(item["secondary_keywords"]),
            usp=item.get("usp"),
            image_url=item.get("image_url"),
            material=item.get("material"),
            dimensions=item.get("dimensions"),
            color=item.get("color"),
            weight=item.get("weight")
        )
        db.add(p)
        db.flush()

        # Build mock generated content
        gen_req = GenerationRequest(
            product_id=p.id,
            name=p.name,
            sku=p.sku,
            brand=p.brand,
            category=p.category,
            price=p.price,
            currency=p.currency,
            image_url=p.image_url,
            features=p.features,
            specifications=p.specifications,
            target_audience=p.target_audience,
            usp=p.usp,
            material=p.material,
            dimensions=p.dimensions,
            color=p.color,
            weight=p.weight,
            primary_keywords=p.primary_keywords,
            secondary_keywords=p.secondary_keywords,
            tone=random.choice(tones),
            word_count="Medium",
            language="English"
        )

        # Run mock generator synchronously for seed
        output, source = mock_gen_gen_sync(gen_req, brand_dict)

        scores = QualityScorer.calculate_scores(
            {
                "name": p.name,
                "brand": p.brand,
                "category": p.category,
                "price": p.price,
                "features": p.features,
                "specifications": p.specifications,
                "target_audience": p.target_audience,
                "primary_keywords": p.primary_keywords,
                "usp": p.usp,
                "image_url": p.image_url,
            },
            output.model_dump(),
            brand_dict
        )

        status_val = random.choice(statuses)

        gen_content = GeneratedContent(
            product_id=p.id,
            title=output.title,
            short_description=output.short_description,
            full_description=output.full_description,
            highlights_json=json.dumps(output.highlights),
            meta_title=output.meta_title,
            meta_description=output.meta_description,
            suggested_keywords_json=json.dumps(output.suggested_keywords),
            warnings_json=json.dumps(output.warnings),
            tone=gen_req.tone,
            language="English",
            word_count_preference="Medium",
            seo_score=scores.seo_score,
            readability_score=scores.readability_score,
            completeness_score=scores.completeness_score,
            brand_tone_score=scores.brand_tone_score,
            quality_score=scores.overall_quality_score,
            status=status_val,
            generation_source="mock",
            is_human_edited=False
        )
        db.add(gen_content)
        db.flush()

        version = ContentVersion(
            generated_content_id=gen_content.id,
            version_number=1,
            content_snapshot_json=json.dumps(output.model_dump()),
            changed_by="Seed Process",
            change_type="Initial Generation"
        )
        db.add(version)

    db.commit()

def mock_gen_gen_sync(request, brand_dict):
    mock = MockGenerator()
    return mock.generate_sync(request, brand_dict)

def generate_sample_files(target_dir: str):
    """
    Generates downloadable sample_products.csv and sample_products.json files.
    """
    os.makedirs(target_dir, exist_ok=True)
    
    # 1. CSV sample
    csv_rows = []
    for item in SAMPLE_50_PRODUCTS:
        row = {
            "productId": item["sku"],
            "sku": item["sku"],
            "productName": item["name"],
            "brand": item["brand"],
            "category": item["category"],
            "price": item["price"],
            "currency": item["currency"],
            "features": "; ".join(item["features"]),
            "specifications": json.dumps(item["specifications"]),
            "targetAudience": item.get("target_audience", ""),
            "primaryKeywords": ", ".join(item["primary_keywords"]),
            "secondaryKeywords": ", ".join(item["secondary_keywords"]),
            "usp": item.get("usp", ""),
            "imageUrl": item.get("image_url", ""),
            "material": item.get("material", ""),
            "dimensions": item.get("dimensions", ""),
            "color": item.get("color", ""),
            "weight": item.get("weight", "")
        }
        csv_rows.append(row)

    csv_path = os.path.join(target_dir, "sample_products.csv")
    df = pd.DataFrame(csv_rows)
    df.to_csv(csv_path, index=False)

    # 2. JSON sample
    json_path = os.path.join(target_dir, "sample_products.json")
    json_payload = {
        "description": "CatalogCraft AI Retail Sample Dataset",
        "total_records": len(SAMPLE_50_PRODUCTS),
        "products": SAMPLE_50_PRODUCTS
    }
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(json_payload, f, indent=2)
